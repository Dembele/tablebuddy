//Writes packages/data/books.ts: the list of installed books the loader merges. A book is a folder here with a _book.ts that
//exports `book` (shape: types/book/book.ts). The public stub book is used only when no other book is installed.
//Run after adding or removing a book: node packages/data/books.js
const fs = require('fs')
const path = require('path')

const here = __dirname
const found = fs.readdirSync(here, {withFileTypes: true})
  .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(here, entry.name, '_book.ts')))
  .map((entry) => entry.name)
  .sort((a, b) => a === 'core' ? -1 : b === 'core' ? 1 : a.localeCompare(b))                                            //core first, then by name
const installed = found.some((name) => name !== 'stub') ? found.filter((name) => name !== 'stub') : found
if (!installed.length) throw new Error('No book in packages/data: expected at least packages/data/stub/_book.ts')

const variable = (name) => name.replace(/[^A-Za-z0-9]+(.)?/g, (_match, letter) => letter ? letter.toUpperCase() : '')
const lines = [
  '//Generated by packages/data/books.js — the installed books, merged by data/loader.ts. Do not edit; not in git.',
  ...installed.map((name) => `import {book as ${variable(name)}} from "./${name}/_book"`),
  '',
  `export const books = [${installed.map(variable).join(', ')}]`,
  ''
]
fs.writeFileSync(path.join(here, 'books.ts'), lines.join('\n'))
console.log(`books.ts: ${installed.join(', ')}`)
